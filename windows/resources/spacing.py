from typing import Final


class Spacing:
    # No spacing
    NONE: Final[int] = 0
    # Tiny spacing (4px)
    XS: Final[int] = 4
    # Small spacing (8px)
    SM: Final[int] = 8
    # Medium spacing (12px)
    MD: Final[int] = 12
    # Large spacing (16px)
    LG: Final[int] = 16
    # Extra large spacing (20px)
    XL: Final[int] = 20
    # Double extra large spacing (24px)
    XXL: Final[int] = 24
